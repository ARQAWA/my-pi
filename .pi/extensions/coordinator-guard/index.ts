// Dev-only project extension of this repository: mechanical guard for Main, the top-level coordinator session.
// Pi loads it only from `.pi/extensions` of a trusted cwd; the shipped package and RQW-agent children
// (noExtensions) never load it. Rules: PROCESS.md, the `json coordinator-rules` block in "Subagent models".
import type { ExtensionAPI, ExtensionContext } from "@earendil-works/pi-coding-agent";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { acquireLock, LOCK_NAME, processStart, releaseLock } from "./lock.ts";
import { canonical, gitCommonDir, isInside, protectedRoots, resolveToolPath } from "./paths.ts";
import { describePairs, describeReviewerProfiles, drawPair, isAllowed, loadRules, restrictionText, type Loaded, type Rules } from "./rules.ts";

const LINK = "PROCESS.md#subagent-models";
const SECTION = "coordinator_rules";
const NOTE_SECTION = "coordinator_note";
// Pi builds a new instance of this extension (and may load the module afresh) on /new, /resume, /fork and /reload,
// so what must outlive them lives on globalThis: the role this chat chose at its start, and this process's start time.
const SHARED = Symbol.for("my-pi.coordinator-guard.shared");
type Shared = { role?: "coordinator" | "direct"; holderPid?: number; start?: string | null };
const shared = (): Shared => ((globalThis as Record<symbol, unknown>)[SHARED] ??= {}) as Shared;

/** `now` is the clock in ms; tests inject it, the default is the real time. */
export type GuardOptions = { root: string; processFile?: string; now?: () => number; randomInt?: (max: number) => number };

/** The line appended to an allowed start's task, so the rule follows ordinary nested `agent` starts. */
export function childInstruction(rules: Rules, now: number = Date.now()): string {
	const parts = [
		`[coordinator-guard] For Main's executor \`agent\` start or restart, pass the category name as model (${Object.keys(rules.agentModels).join(", ")}); thinking is optional; the guard draws the pair uniformly at random (${describePairs(rules, now)}); reviewer-profile calls instead use their exact reviewerProfiles pair; a start with fork_turns "all" passes no model, the fork inherits the caller's model; pass this line on in its task.`,
	];
	const temporary = restrictionText(rules, now);
	if (temporary) parts.push(temporary);
	return parts.join(" ");
}

export function promptSection(loaded: Loaded, processFile: string, now: number = Date.now()): string {
	const head = "Generated by the coordinator-guard extension from the coordinator-rules block of PROCESS.md on every turn. It binds Main, the top-level coordinator session of this repository; a subagent that inherits this text follows its own brief instead.";
	if (!loaded.ok) {
		return [
			head,
			`- ERROR: the coordinator-rules block in ${processFile} is unreadable: ${loaded.error}`,
			"- Until it is fixed, every agent start and restart is blocked. Tell the owner at once.",
			"- Main still never edits or writes repository files itself.",
		].join("\n");
	}
	const { rules } = loaded;
	const temporary = restrictionText(rules, now);
	return [
		head,
		"- Main delegates research, edits, checks and fixes to subagents. When the owner asks Main to do such work personally (for example \"ты сам\" or \"you do it\"), Main objects and proposes a subagent for it; only an explicit owner override lets Main do that work itself. Main never edits or writes files in the checkout or its worktrees (edit and write there are blocked).",
		`- Every executor start or restart by Main passes the category name as model (${Object.keys(rules.agentModels).join(", ")}); thinking is optional. The guard draws the pair uniformly at random: ${describePairs(rules, now)} (${LINK}).`,
		`- Reviewer-profile starts and restarts instead use the exact pair for their agent_type: ${describeReviewerProfiles(rules)}. Existing agents keep their model through send/resume and are not restarted merely to switch models.`,
		"- An `agent` start with `fork_turns: \"all\"` passes no model: the fork inherits the caller's model, so the prompt cache is reused, and the guard draws nothing and rewrites nothing.",
		...(temporary ? [`- ${temporary}`] : []),
	].join("\n");
}

/** The short system note of a session that is not the coordinator: the coordinator rules do not bind it. */
export function directNote(holderPid: number | undefined): string {
	const who = holderPid === undefined ? "Another Pi session" : `Another Pi session (pid ${holderPid})`;
	return `${who} holds the coordinator lock of this repository, so this session is a normal direct agent and stays one for its whole life. The coordinator rules of AGENTS.md and PROCESS.md (delegate all work to subagents, allowed model pairs, no direct edits) do not apply here: work with your own tools as the user asks.`;
}

/** A restart inherits its profile from the latest persisted child record when agent_type is omitted. */
function profileName(input: Record<string, any>, ctx: ExtensionContext): string | undefined {
	if (typeof input.agent_type === "string") return input.agent_type;
	if ((input.action ?? "start") !== "restart" || typeof input.id !== "string") return undefined;
	const match = /^(?:agent#)?([1-9]\d*)$/.exec(input.id);
	const id = match ? Number(match[1]) : NaN;
	if (!Number.isSafeInteger(id)) return undefined;
	const entries = ctx.sessionManager.getBranch();
	for (let i = entries.length - 1; i >= 0; i--) {
		const entry = entries[i];
		if (entry.type !== "custom" || entry.customType !== "rqw-agent-child") continue;
		const data = entry.data as { kind?: unknown; id?: unknown; config?: { profile?: { name?: unknown } } } | undefined;
		if (data?.kind !== "agent" || data.id !== id) continue;
		const name = data.config?.profile?.name;
		return typeof name === "string" ? name : undefined;
	}
	return undefined;
}

function editPaths(input: any): string[] | undefined {
	if (!input || typeof input !== "object") return undefined;
	const paths: unknown[] = [];
	if (input.path !== undefined) paths.push(input.path);
	for (const list of [input.edits, input.files]) {
		if (Array.isArray(list)) for (const entry of list) if (entry && typeof entry === "object" && entry.path !== undefined) paths.push(entry.path);
	}
	return paths.length && paths.every((p) => typeof p === "string" && p !== "") ? (paths as string[]) : undefined;
}

export function createCoordinatorGuard(options: GuardOptions) {
	const root = resolve(options.root);
	const processFile = options.processFile ?? join(root, "PROCESS.md");
	const clock = options.now ?? Date.now;

	return function coordinatorGuard(pi: ExtensionAPI) {
		// Enforcing until session_start shows another live process holds the lock; a missing lock or a failed lock
		// operation also keeps the guard on. The role is chosen once, when a chat starts: a chat that began as a
		// normal direct agent stays normal through /new, /resume, /fork and /reload, even after the coordinator quits;
		// only a chat started afterwards takes the lock (see SHARED above for how it survives the new instance).
		const saved = shared();
		let coordinator = saved.role !== "direct";
		let holderPid = saved.holderPid;
		const common = gitCommonDir(root);
		// The lock is macOS only; elsewhere there is no lock and the guard works as it did before it.
		const lockFile = common && process.platform === "darwin" ? join(common, LOCK_NAME) : undefined;
		// @ts-expect-error TS7 misreads this cached nullable process start as always nullish.
		const self = () => ({ pid: process.pid, start: (shared().start ??= processStart(process.pid) ?? null) ?? undefined });

		pi.on("session_start", (event, ctx) => {
			const reason = (event as { reason?: string }).reason ?? "startup";
			const state = shared();
			let notice: string | undefined;
			if (lockFile && reason !== "startup" && state.role === "direct") {
				coordinator = false; // a normal chat keeps its role; the lock is not touched
			} else if (lockFile) {
				try {
					const got = acquireLock(lockFile, { ...self(), sessionId: ctx.sessionManager.getSessionId() });
					coordinator = got.held;
					holderPid = got.held ? undefined : got.holder?.pid;
					state.role = coordinator ? "coordinator" : "direct";
					state.holderPid = holderPid;
					if (got.held && (got.fresh || reason === "startup")) notice = "coordinator-guard: this session is the coordinator (exclusive lock taken).";
					else if (!got.held) notice = `coordinator-guard: another session (pid ${holderPid ?? "unknown"}) is the coordinator; this chat is a normal direct agent. Already-open normal chats stay normal when the coordinator quits; only a chat started afterwards takes the coordinator role.`;
				} catch (error) {
					coordinator = true;
					notice = `coordinator-guard: coordinator lock failed (${(error as Error).message}); guard stays on.`;
				}
			}
			if (!ctx.hasUI) return;
			if (!coordinator) ctx.ui.setStatus("coordinator-guard", "coordinator-guard: direct agent");
			else {
				const loaded = loadRules(processFile);
				ctx.ui.setStatus("coordinator-guard", loaded.ok ? "coordinator-guard on" : "coordinator-guard: rules unreadable");
			}
			if (notice) ctx.ui.notify(notice, "info");
		});

		// Only a quit releases the lock (Ctrl+D, double Ctrl+C, /quit and the SIGTERM/SIGHUP path all end in
		// session_shutdown with reason "quit"); /new, /resume, /fork and /reload shut down with another reason.
		pi.on("session_shutdown", (event) => {
			if ((event as { reason?: string }).reason !== "quit") return;
			if (lockFile) releaseLock(lockFile, self());
			shared().role = undefined;
		});

		pi.on("before_agent_start", (event) => {
			if (!coordinator) {
				event.systemPromptOptions.sections[NOTE_SECTION] = directNote(holderPid);
				return;
			}
			event.systemPromptOptions.sections[SECTION] = promptSection(loadRules(processFile), processFile, clock());
		});

		pi.on("tool_call", (event, ctx) => {
			if (!coordinator) return undefined;
			const name = event.toolName;
			const input = event.input as Record<string, any>;

			if (name === "edit" || name === "write") {
				const paths = editPaths(input);
				if (!paths) return { block: true, reason: `coordinator-guard: ${name} without a readable path is blocked for Main.` };
				const roots = protectedRoots(root);
				for (const path of paths) {
					const target = canonical(resolveToolPath(path, ctx.cwd));
					const hit = roots.find((r) => isInside(target, r));
					if (hit) {
						return { block: true, reason: `coordinator-guard: Main does not edit repo files (${path} is inside ${hit}); start an agent subagent with an allowed model to change it.` };
					}
				}
				return undefined;
			}

			if (name !== "agent") return undefined;
			const action = input.action ?? "start";
			const starts = action === "start" || action === "restart";
			if (!starts) return undefined;

			const loaded = loadRules(processFile);
			if (!loaded.ok) return { block: true, reason: `coordinator-guard: coordinator-rules in ${processFile} is unreadable: ${loaded.error}` };
			const { rules } = loaded;
			const now = clock();
			const allowed = `allowed: ${describePairs(rules, now)}; reviewer profiles: ${describeReviewerProfiles(rules)} (${LINK})`;
			// A fork inherits the caller's model and prompt so its first request reuses the prompt cache: no category, no draw.
			if (input.fork_turns !== "all") {
				const profile = profileName(input, ctx);
				if (profile !== undefined && Object.hasOwn(rules.reviewerProfiles, profile)) {
					if (typeof input.model !== "string" || typeof input.thinking !== "string" || !isAllowed(rules, input.model, input.thinking, now, profile)) {
						return { block: true, reason: `coordinator-guard: give the exact model and thinking for reviewer ${profile}; ${allowed}.` };
					}
				} else {
					const pair = typeof input.model === "string" ? drawPair(rules, input.model, now, options.randomInt) : undefined;
					if (!pair) {
						return { block: true, reason: `coordinator-guard: pass the category name as model (${Object.keys(rules.agentModels).join(", ")}); the guard draws the pair uniformly at random. Main must not choose an explicit executor pair; ${allowed}.` };
					}
					[input.model, input.thinking] = pair;
				}
			}
			if (typeof input.task === "string") input.task = `${input.task}\n\n${childInstruction(rules, now)}`;
			return undefined;
		});
	};
}

// The checkout this file lives in: .pi/extensions/coordinator-guard/index.ts -> three levels up.
export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");

export default createCoordinatorGuard({ root: ROOT });
