import assert from "node:assert/strict";
import { it } from "node:test";
import { call, text, world } from "./synthetic/world.ts";

it("disables an open list without saving and ignores skill activation and restore", async (t) => {
	const w = await world(t);
	const held = w.model.hold(request => request.context.messages.some(message => message.role === "toolResult" && message.toolName === "todo"));
	w.model.script(call("todo", { items: [{ id: "a", text: "Open task", status: "active" }] }), text("done"));
	w.type("$todo start");
	w.press("\r");
	await w.until(() => held.arrived, "open list");
	w.see("Open task");
	const runner = w.session.extensionRunner!;
	const bus = (w.runtime.services.resourceLoader as any).eventBus;
	const before = w.jsonl().length;
	bus.emit("rqw-todo:disable:v1", { ctx: runner.createContext() });
	assert.equal(w.jsonl().length, before);
	assert.ok(!runner.getActiveTools().includes("todo"));
	w.notSee("▸ Open task");
	held.reply(text("finished"));
	await w.settle();
	assert.equal(w.requests.filter(request => JSON.stringify(request.context.messages).includes("Остались открытые пункты")).length, 0);
	await runner.emit({ type: "session_start", reason: "startup" });
	await runner.emitInput("/skill:todo work", undefined, "interactive");
	assert.ok(!runner.getActiveTools().includes("todo"));
	const messages = await runner.emitContext(w.session.agent.state.messages);
	assert.ok(!JSON.stringify(messages).includes("Текущий список дел:"));
	assert.ok(!JSON.stringify(messages).includes("Open task"));
	assert.deepEqual(w.errors, []);
	await w.dispose();
	assert.deepEqual(w.patched(), []);
});
