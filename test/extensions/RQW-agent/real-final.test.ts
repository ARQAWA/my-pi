import assert from "node:assert/strict";
import { test } from "node:test";
import { AgentSession, createEventBus } from "@earendil-works/pi-coding-agent";
import { registerRunningCounts } from "../../../extensions/RQW-agent/running-counts.ts";
import { registerHerdrActivity } from "../../../extensions/RQW-agent/herdr-state.ts";

test("herdr tracks native wait and background after final, then restores its handlers", async t => {
	const env = process.env.HERDR_ENV; process.env.HERDR_ENV = "1";
	t.after(() => { if (env === undefined) delete process.env.HERDR_ENV; else process.env.HERDR_ENV = env; });
	const states: string[] = [];
	const start = () => { states.push("working"); };
	const settled = (_event: unknown, ctx: any) => { if (ctx.isIdle()) states.push("idle"); };
	const herdr = { path: "herdr-agent-state.ts", handlers: new Map([["agent_start", [start]], ["agent_settled", [settled]]]) };
	const manager = {};
	const session: any = Object.assign(Object.create(AgentSession.prototype), { sessionManager: manager, _isAgentRunActive: false, _extensionRunner: { extensions: [herdr] } });
	const ctx: any = { mode: "tui", sessionManager: manager, isIdle: () => session.isIdle };
	const events = createEventBus();
	let value = 0, changed = (_value: unknown) => {};
	const source = { version: 1, snapshot: () => ({ agents: value }), subscribe(fn: typeof changed) { changed = fn; return () => {}; } };
	events.on("rqw:running-counts:request", (request: any) => request.reply(source));
	const hooks = new Map<string, Function[]>();
	const pi: any = { events, on(name: string, fn: Function) { hooks.set(name, [...hooks.get(name) ?? [], fn]); } };
	const counts = registerRunningCounts(pi); registerHerdrActivity(pi, counts);
	const fire = async (name: string) => { for (const fn of herdr.handlers.get(name) ?? []) await fn({}, ctx); for (const fn of hooks.get(name) ?? []) await fn({}, ctx); };
	await fire("session_start");
	session._isAgentRunActive = true; await fire("agent_start");
	assert.deepEqual(states, ["working"], "an open native wait stays working");
	session._isAgentRunActive = false; await fire("agent_settled");
	assert.deepEqual(states, ["working", "idle"]);
	value = 1; changed(source.snapshot());
	assert.deepEqual(states, ["working", "idle", "working"]);
	value = 0; changed(source.snapshot());
	assert.deepEqual(states, ["working", "idle", "working", "idle"]);
	await fire("session_shutdown");
	assert.equal(herdr.handlers.get("agent_settled")![0], settled);
});

test("unknown herdr runner shape falls back to stock", async t => {
	const env = process.env.HERDR_ENV; process.env.HERDR_ENV = "1";
	t.after(() => { if (env === undefined) delete process.env.HERDR_ENV; else process.env.HERDR_ENV = env; });
	const original = () => {};
	const herdr = { path: "herdr-agent-state.ts", handlers: new Map([["agent_settled", [original]]]) };
	const manager = {};
	const session: any = Object.assign(Object.create(AgentSession.prototype), { sessionManager: manager, _isAgentRunActive: false, _extensionRunner: { extensions: [herdr] } });
	const hooks = new Map<string, Function[]>(); const events = createEventBus();
	const pi: any = { events, on(name: string, fn: Function) { hooks.set(name, [...hooks.get(name) ?? [], fn]); } };
	registerHerdrActivity(pi, registerRunningCounts(pi));
	for (const fn of hooks.get("session_start") ?? []) await fn({}, { mode: "tui", sessionManager: manager, isIdle: () => session.isIdle });
	assert.equal(herdr.handlers.get("agent_settled")![0], original);
	for (const fn of hooks.get("session_shutdown") ?? []) await fn({}, {});
});
