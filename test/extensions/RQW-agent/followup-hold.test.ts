import assert from "node:assert/strict";
import { test } from "node:test";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { Agent } from "@earendil-works/pi-agent-core";
import { AgentSession, createEventBus } from "@earendil-works/pi-coding-agent";
import agent from "../../../extensions/RQW-agent/index.ts";

test("top-level session holds user follow-ups while a background job runs", async t => {
	t.mock.timers.enable({ apis: ["setTimeout"] });
	const root = mkdtempSync(join(tmpdir(), "rqw-followup-"));
	const codex = process.env.CODEX_HOME, agentDir = process.env.PI_CODING_AGENT_DIR;
	process.env.CODEX_HOME = join(root, "codex"); process.env.PI_CODING_AGENT_DIR = join(root, "pi");
	t.after(() => { if (codex === undefined) delete process.env.CODEX_HOME; else process.env.CODEX_HOME = codex; if (agentDir === undefined) delete process.env.PI_CODING_AGENT_DIR; else process.env.PI_CODING_AGENT_DIR = agentDir; rmSync(root, { recursive: true, force: true }); });
	const hooks = new Map<string, ((event: any, ctx: any) => unknown)[]>();
	const events = createEventBus();
	let processes = 1;
	let changed = (_counts: unknown) => {};
	const source = { version: 1, snapshot: () => ({ agents: 0, backgroundProcesses: processes }), subscribe: (listener: typeof changed) => { changed = listener; return () => {}; } };
	events.on("rqw:running-counts:request", (request: any) => request.reply(source));
	const manager = { getSessionId: () => "main", getEntries: () => [], getBranch: () => [], getSessionFile: () => undefined, getLeafEntry: () => undefined };
	const session = Object.assign(Object.create(AgentSession.prototype), { sessionManager: manager, agent: new Agent(), _isAgentRunActive: false });
	const ctx: any = { cwd: root, mode: "tui", sessionManager: manager, isIdle: () => session.isIdle, ui: { notify() {}, setStatus() {} } };
	const pi: any = { events, on: (name: string, fn: any) => hooks.set(name, [...hooks.get(name) ?? [], fn]), registerCommand() {}, registerTool() {}, registerEntryRenderer() {}, getThinkingLevel: () => "off", getActiveTools: () => [] };
	agent(pi);
	for (const hook of hooks.get("session_start") ?? []) await hook({}, ctx);
	const queue = (session.agent as any).followUpQueue;
	const user = { role: "user", content: [{ type: "text", text: "later" }], timestamp: 1 };
	const custom = { role: "custom", content: "notice", timestamp: 2 };
	queue.enqueue(user); queue.enqueue(custom);
	assert.deepEqual(queue.drain(), [custom]);
	assert.equal(queue.hasItems(), false);
	processes = 0;
	assert.deepEqual(queue.drain(), [user]);
	processes = 1; changed(source.snapshot());
	const started: string[] = [];
	session._steeringMessages = [];
	session._startRun = async (trigger: any) => {
		started.push(trigger.prompt);
		for (const hook of hooks.get("message_start") ?? []) await hook({ message: { role: "user" } }, ctx);
	};
	queue.enqueue(user);
	processes = 0; changed(source.snapshot());
	t.mock.timers.tick(0);
	await Promise.resolve();
	assert.deepEqual(started, ["later"]);
	await Promise.resolve(); await Promise.resolve();
	queue.enqueue({ role: "user", content: [{ type: "text", text: "late input" }], timestamp: 3 });
	t.mock.timers.tick(0);
	await Promise.resolve();
	assert.deepEqual(started, ["later", "late input"], "an input finishing after the background ends starts a run");
	await Promise.resolve(); await Promise.resolve();
	let finish!: () => void;
	session._startRun = (trigger: any) => {
		started.push(trigger.prompt);
		for (const hook of hooks.get("message_start") ?? []) hook({ message: { role: "user" } }, ctx);
		return new Promise<void>(resolve => { finish = resolve; });
	};
	queue.enqueue({ role: "user", content: [{ type: "text", text: "first" }] });
	t.mock.timers.tick(0);
	queue.enqueue({ role: "user", content: [{ type: "text", text: "second" }] });
	finish(); await Promise.resolve(); await Promise.resolve();
	t.mock.timers.tick(0);
	assert.deepEqual(started, ["later", "late input", "first", "second"], "a follow-up arriving during settlement also starts");
	finish(); await Promise.resolve(); await Promise.resolve();
	const replies: any[] = [];
	events.emit("rqw:stop-background:v1", { sessionId: "main", reply: (part: any) => replies.push(part) });
	assert.deepEqual(replies, [{ agents: 0 }]);
	for (const hook of hooks.get("session_shutdown") ?? []) await hook({}, ctx);
});

test("shutdown restores an in-flight follow-up without discarding custom messages", async t => {
	t.mock.timers.enable({ apis: ["setTimeout"] });
	const root = mkdtempSync(join(tmpdir(), "rqw-followup-shutdown-"));
	const codex = process.env.CODEX_HOME, agentDir = process.env.PI_CODING_AGENT_DIR;
	process.env.CODEX_HOME = join(root, "codex"); process.env.PI_CODING_AGENT_DIR = join(root, "pi");
	t.after(() => { if (codex === undefined) delete process.env.CODEX_HOME; else process.env.CODEX_HOME = codex; if (agentDir === undefined) delete process.env.PI_CODING_AGENT_DIR; else process.env.PI_CODING_AGENT_DIR = agentDir; rmSync(root, { recursive: true, force: true }); });
	const hooks = new Map<string, ((event: any, ctx: any) => unknown)[]>();
	const events = createEventBus();
	let processes = 1, changed = (_value: unknown) => {};
	const source = { version: 1, snapshot: () => ({ agents: 0, backgroundProcesses: processes }), subscribe: (listener: typeof changed) => { changed = listener; return () => {}; } };
	events.on("rqw:running-counts:request", (request: any) => request.reply(source));
	const manager = { getSessionId: () => "main", getEntries: () => [], getBranch: () => [], getSessionFile: () => undefined, getLeafEntry: () => undefined };
	const session = Object.assign(Object.create(AgentSession.prototype), { sessionManager: manager, agent: new Agent(), _isAgentRunActive: false, _steeringMessages: [], _followUpMessages: ["later"], _emitQueueUpdate() {} });
	let draft = "draft";
	const ctx: any = { cwd: root, mode: "tui", sessionManager: manager, isIdle: () => session.isIdle, ui: { notify() {}, setStatus() {}, getEditorText: () => draft, setEditorText: (text: string) => { draft = text; } } };
	const pi: any = { events, on: (name: string, fn: any) => hooks.set(name, [...hooks.get(name) ?? [], fn]), registerCommand() {}, registerTool() {}, registerEntryRenderer() {}, getThinkingLevel: () => "off", getActiveTools: () => [] };
	agent(pi);
	for (const hook of hooks.get("session_start") ?? []) await hook({}, ctx);
	const queue = (session.agent as any).followUpQueue;
	queue.enqueue({ role: "user", content: [{ type: "text", text: "later" }], timestamp: 1 });
	let finish!: () => void;
	session._startRun = () => new Promise<void>(resolve => { finish = resolve; });
	processes = 0; changed(source.snapshot()); t.mock.timers.tick(0);
	assert.ok(finish);
	const custom = { role: "custom", content: "notice" };
	queue.enqueue(custom);
	for (const hook of hooks.get("session_shutdown") ?? []) await hook({}, ctx);
	assert.equal(draft, "later\n\ndraft");
	assert.deepEqual(queue.messages, [custom]);
	finish(); await Promise.resolve(); await Promise.resolve();
	assert.deepEqual(queue.messages, [custom]);
});
