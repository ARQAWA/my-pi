// Adapted from extensions/RQW-codex/test/web-schema.test.ts at git commit a85b810e924010f35387045fc0cbbd9a1e7173cc.
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { describe, test } from "node:test";
import { parseCommands, WEB_INSTRUCTIONS, WEB_TOOLS } from "../../../extensions/RQW-web/core/web-commands.ts";
import { canonicalNativeTools } from "../../../extensions/RQW-web/vendor/wire.ts";

const snapshot = readFileSync(new URL("../../../extensions/RQW-web/core/web-native-tools.json", import.meta.url));
const tools = JSON.parse(snapshot.toString());
const digest = (value: string | Buffer) => createHash("sha256").update(value).digest("hex");

// Generated by the official Rust pipeline, not an independently invented tool schema.
describe("rqw-search native web", () => {
test("reserved declaration matches the full pinned official Codex wire snapshot", () => {
	assert.equal(digest(snapshot), "072a146598ac4d4293cd9deeb69fc1d96a0fbf5fdaaf5174cc559d2c96de48dc");
	assert.deepEqual(WEB_TOOLS, tools);
	assert.deepEqual(canonicalNativeTools(WEB_TOOLS), tools);
	assert.equal(tools[0].description, "Tools in the web namespace.");
	assert.equal(digest(tools[0].tools[0].description), "1f3879b44690eb7aad9ba97351acda16c4d0c26847bcb4af2964d5989404407e");
});

test("wire schema preserves all native fields, descriptions and official normalization", () => {
	const run = tools[0].tools[0];
	assert.equal(run.strict, false);
	assert.equal(run.name, "run");
	const schema = run.parameters;
	assert.deepEqual(Object.keys(schema.properties), ["click", "finance", "find", "image_query", "open", "response_length", "screenshot", "search_query", "sports", "time", "weather"]);
	assert.deepEqual(schema.properties.click.items.required, ["id", "ref_id"]);
	assert.deepEqual(schema.properties.find.items.required, ["pattern", "ref_id"]);
	assert.equal(schema.properties.search_query.description, "Query the internet search engine for a given list of queries.");
	assert.equal(schema.properties.search_query.items.properties.recency.description, "Whether to filter by recency, as a number of recent days.");
	assert.deepEqual(schema.properties.sports.items.properties.league.enum, ["nba", "wnba", "nfl", "nhl", "mlb", "epl", "ncaamb", "ncaawb", "ipl"]);
	const serialized = JSON.stringify(schema);
	for (const field of ["additionalProperties", "minimum", "format", "$ref", "$defs", "definitions"]) assert.equal(serialized.includes(`"${field}"`), false, field);
});

test("the full declaration does not enable non-text commands in the CLI executor", () => {
	const search_query = [{ q: "official documentation" }];
	for (const name of ["image_query", "screenshot", "finance", "weather", "sports", "time"]) {
		for (const extra of [{}, { search_query }]) {
			assert.throws(() => parseCommands(JSON.stringify({ ...extra, [name]: [{}] }), "short"), /invalid_commands/, name);
		}
	}
	assert.match(WEB_INSTRUCTIONS, /Only search_query, open, click and find may be executed/);
	assert.match(WEB_INSTRUCTIONS, /Other commands in the reserved declaration are unavailable/);
});

});
